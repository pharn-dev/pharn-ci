// ---- yarn berry ----
const BERRY_HEAD =
  '# This file is generated by running "yarn install" inside your project.\n# Manual changes might be lost - proceed with caution!\n\n__metadata:\n  version: 8\n  cacheKey: 10c0\n\n';
const BERRY_LP =
  '"left-pad@npm:^1.3.0":\n  version: 1.3.0\n  resolution: "left-pad@npm:1.3.0"\n  checksum: 10c0/aa\n  languageName: node\n  linkType: hard\n';
const BERRY_BASE = `${BERRY_HEAD}${BERRY_LP}`;
function berry(header: string, resolution: string, linkType = "hard", version = "1.0.0"): string {
  return `${BERRY_HEAD}"${header}":\n  version: ${version}\n  resolution: "${resolution}"\n  checksum: 10c0/ee\n  languageName: node\n  linkType: ${linkType}\n\n${BERRY_LP}`;
}

// ---- poetry ----
const POETRY_TOP = "# This file is automatically @generated by Poetry 1.8.3 and should not be changed by hand.\n\n";
const POETRY_REQ =
  '[[package]]\nname = "requests"\nversion = "2.32.3"\ndescription = "Python HTTP for Humans."\noptional = false\npython-versions = ">=3.8"\nfiles = [\n    {file = "requests-2.32.3-py3-none-any.whl", hash = "sha256:aa"},\n]\n\n';
const POETRY_META = '[metadata]\nlock-version = "2.0"\npython-versions = "^3.11"\ncontent-hash = "abc"\n';
const POETRY_BASE = `${POETRY_TOP}${POETRY_REQ}${POETRY_META}`;
const PURL = "https://evil.example/evil-pkg-1.0.0.tar.gz";
const POETRY_EVIL_TOP =
  '[[package]]\nname = "evil-pkg"\nversion = "1.0.0"\ndescription = ""\noptional = false\npython-versions = "*"\nfiles = []\n';
function poetry(evil: string): string {
  return `${POETRY_TOP}${evil}\n${POETRY_REQ}${POETRY_META}`;
}

// ---- uv ----
const UV_TOP = 'version = 1\nrequires-python = ">=3.11"\n\n';
function uvApp(extraDeps: string, extraReq: string): string {
  return `[[package]]\nname = "app"\nversion = "0.1.0"\nsource = { editable = "." }\ndependencies = [\n${extraDeps}    { name = "httpx" },\n]\n\n[package.metadata]\nrequires-dist = [\n${extraReq}    { name = "httpx", specifier = ">=0.27" },\n]\n\n`;
}
function uvHttpx(v = "0.27.0"): string {
  return `[[package]]\nname = "httpx"\nversion = "${v}"\nsource = { registry = "https://pypi.org/simple" }\nsdist = { url = "https://files.pythonhosted.org/packages/httpx-${v}.tar.gz", hash = "sha256:aa", size = 1 }\nwheels = [\n    { url = "https://files.pythonhosted.org/packages/httpx-${v}-py3-none-any.whl", hash = "sha256:bb", size = 2 },\n]\n`;
}
const UV_BASE = `${UV_TOP}${uvApp("", "")}${uvHttpx()}`;
function uvWith(evilPackage: string, req: string): string {
  return `${UV_TOP}${uvApp('    { name = "evil-pkg" },\n', req)}${evilPackage}\n${uvHttpx()}`;
}
const UV_EVIL = (source: string) => `[[package]]\nname = "evil-pkg"\nversion = "1.0.0"\n${source}`;

